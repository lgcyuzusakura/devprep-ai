CREATE TABLE job_profiles (
    id TEXT PRIMARY KEY,
    payload_json TEXT NOT NULL,
    revision INTEGER NOT NULL DEFAULT 0,
    updated_at TEXT NOT NULL
);
CREATE TABLE job_opportunities (
    id TEXT PRIMARY KEY,
    source_key VARCHAR(64) UNIQUE,
    payload_json TEXT NOT NULL,
    revision INTEGER NOT NULL DEFAULT 0,
    updated_at TEXT NOT NULL
);
CREATE TABLE job_materials (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT NOT NULL UNIQUE,
    job_id TEXT NOT NULL REFERENCES job_opportunities(id) ON DELETE CASCADE,
    payload_json TEXT NOT NULL,
    inputs_json TEXT NOT NULL,
    model TEXT NOT NULL,
    parent_id TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX idx_job_materials_job ON job_materials(job_id, seq);
CREATE TABLE job_events (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES job_opportunities(id) ON DELETE CASCADE,
    status TEXT NOT NULL,
    note TEXT NOT NULL,
    material_id TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE job_attachments (
    id TEXT PRIMARY KEY,
    material_id TEXT NOT NULL REFERENCES job_materials(id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    content_base64 TEXT NOT NULL,
    created_at TEXT NOT NULL
);
