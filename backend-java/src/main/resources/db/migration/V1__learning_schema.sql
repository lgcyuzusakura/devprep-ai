CREATE TABLE knowledge_points (
    id TEXT PRIMARY KEY,
    domain TEXT NOT NULL,
    title TEXT NOT NULL,
    summary TEXT NOT NULL,
    prerequisites_json TEXT NOT NULL DEFAULT '[]',
    next_review_at TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE materials (
    id TEXT PRIMARY KEY,
    filename TEXT NOT NULL,
    title TEXT NOT NULL,
    source_type TEXT NOT NULL,
    imported_at TEXT NOT NULL,
    content TEXT NOT NULL
);

CREATE TABLE material_chunks (
    id TEXT PRIMARY KEY,
    material_id TEXT NOT NULL REFERENCES materials(id) ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL,
    heading TEXT NOT NULL,
    content TEXT NOT NULL,
    UNIQUE (material_id, chunk_index)
);

CREATE TABLE questions (
    id TEXT PRIMARY KEY,
    knowledge_point_id TEXT NOT NULL REFERENCES knowledge_points(id),
    question_type TEXT NOT NULL CHECK (question_type IN ('single_choice', 'short_answer')),
    stem TEXT NOT NULL,
    options_json TEXT NOT NULL DEFAULT '[]',
    answer_json TEXT NOT NULL,
    explanation TEXT NOT NULL,
    rubric_json TEXT NOT NULL DEFAULT '[]',
    source_material_id TEXT REFERENCES materials(id),
    status TEXT NOT NULL DEFAULT 'reviewed'
);

CREATE TABLE attempts (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT NOT NULL UNIQUE,
    question_id TEXT NOT NULL REFERENCES questions(id),
    knowledge_point_id TEXT NOT NULL REFERENCES knowledge_points(id),
    answer_json TEXT NOT NULL,
    score DOUBLE PRECISION NOT NULL CHECK (score >= 0 AND score <= 1),
    is_correct INTEGER NOT NULL CHECK (is_correct IN (0, 1)),
    rubric_hits_json TEXT NOT NULL DEFAULT '[]',
    created_at TEXT NOT NULL
);

CREATE INDEX idx_chunks_material ON material_chunks(material_id, chunk_index);
CREATE INDEX idx_questions_point ON questions(knowledge_point_id, id);
CREATE INDEX idx_attempts_created ON attempts(created_at DESC, seq DESC);
CREATE INDEX idx_attempts_point ON attempts(knowledge_point_id, created_at DESC, seq DESC);
